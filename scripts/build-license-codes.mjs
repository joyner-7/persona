import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "output/license-codes/persona_codes.txt");
const targetPath = resolve(root, "lib/auth/license-codes.ts");

const codes = readFileSync(sourcePath, "utf8")
  .split(/\r?\n/)
  .map((code) => code.trim().toUpperCase())
  .filter(Boolean);

const uniqueCodes = Array.from(new Set(codes)).sort();
const invalidCodes = uniqueCodes.filter(
  (code) => code !== "CE" && !/^[A-Z]{6}$/.test(code)
);

if (invalidCodes.length > 0) {
  throw new Error(`Invalid license codes: ${invalidCodes.slice(0, 5).join(", ")}`);
}

const content = `// Generated by scripts/build-license-codes.mjs. Do not edit by hand.
export const LICENSE_CODES: string[] = ${JSON.stringify(uniqueCodes)};
`;

writeFileSync(targetPath, content, "utf8");

console.log(`Generated ${uniqueCodes.length} license codes at ${targetPath}`);
